  TOTAL_OK INT NULL,
  TOTAL_KO INT NULL,
  TOTAL_WARN INT NULL,
  DURACION_MS INT NULL,
  PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS SMK_RESULTADO (
  ID INT NOT NULL AUTO_INCREMENT,
  EJECUCION_ID INT NULL,
  TEST_CODIGO VARCHAR(255) NULL,
  TEST_NOMBRE VARCHAR(255) NULL,
  CATEGORIA VARCHAR(255) NULL,
  SISTEMA VARCHAR(255) NULL,
  RESULTADO VARCHAR(255) NULL,
