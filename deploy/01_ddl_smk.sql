CREATE TABLE IF NOT EXISTS SMK_TEST (
  ID INT NOT NULL AUTO_INCREMENT,
  CODIGO VARCHAR(255) NULL,
  NOMBRE VARCHAR(255) NULL,
  CATEGORIA VARCHAR(255) NULL,
  SISTEMA VARCHAR(255) NULL,
  DESCRIPCION VARCHAR(4000) NULL,
  CRITICIDAD VARCHAR(255) NULL,
  ACTIVO BOOLEAN NULL,
  MOTIVO_INACTIVO VARCHAR(255) NULL,
  ORIGEN_ALTA VARCHAR(255) NULL,
  ORDEN INT NULL,
  UMBRAL_MS INT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_SMK_TEST_CODIGO (CODIGO)
);

CREATE TABLE IF NOT EXISTS SMK_EJECUCION (
